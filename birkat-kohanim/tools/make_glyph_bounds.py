#!/usr/bin/env python3
"""Generate ../glyph-bounds.lua: the ink outline of each Hebrew letter in
Taamey David CLM Medium as a convex hull, so spiral.lua can centre the
drawing by its ink even where letters are turned (a turned letter's box
reaches past its ink; LuaTeX's boxes also include side bearings).

Usage: python3 make_glyph_bounds.py [path/to/TaameyDavidCLM-Medium.ttf]
Needs fontTools (pip install fonttools). The default is the copy in
shared/fonts/. Points are font units (y up, origin at the left end of the
baseline). The hull is of the outline's on- and off-curve points, which
contain its curves. The font is GPL with the font exception (Culmus
Project).
"""
import os
import sys

from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = (sys.argv[1] if len(sys.argv) > 1 else
        os.path.join(HERE, '..', '..', 'shared', 'fonts', 'TaameyDavidCLM-Medium.ttf'))
OUT = os.path.join(HERE, '..', 'glyph-bounds.lua')


def hull(points):
    """Convex hull, counter-clockwise (Andrew's monotone chain)."""
    pts = sorted(set(points))
    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lower, upper = [], []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]


font = TTFont(FONT)
cmap = font.getBestCmap()
glyf = font['glyf']
lines = []
for cp in range(0x05D0, 0x05EB):             # alef to tav, finals included
    coords, _, _ = glyf[cmap[cp]].getCoordinates(glyf)
    h = hull([tuple(p) for p in coords])
    lines.append('  [0x%04X] = { %s },' % (cp, ', '.join('%d, %d' % p for p in h)))
with open(OUT, 'w', encoding='ascii') as f:
    f.write('-- glyph-bounds.lua: ink outline of each Hebrew letter in Taamey David\n'
            '-- CLM Medium, as a convex hull: x1, y1, x2, y2, ... in font units.\n'
            '-- Generated by tools/make_glyph_bounds.py; do not edit by hand.\n'
            'return {\n  units_per_em = %d,\n' % font['head'].unitsPerEm)
    f.write('\n'.join(lines) + '\n}\n')
print(len(lines), 'letters')
