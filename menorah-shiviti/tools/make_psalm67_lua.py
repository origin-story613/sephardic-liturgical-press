#!/usr/bin/env python3
"""Generate ../psalm67.lua from the Sefaria export of Psalm 67.

Usage: python3 make_psalm67_lua.py
Source: "Tanach with Ta'amei Hamikra" (Westminster Leningrad Codex, public
domain). Letters only (Yosef): nikud, te'amim, sof pasuq and paseq are
removed, and a maqaf becomes a word break. Spellings follow Yosef's siddur
where it differs (SIDDUR below). Words of the divine
name Elohim are written as \\u{...} code-point escapes, so the name never
appears spelled out in the repo.
"""
import json
import os
import re
import urllib.parse
import urllib.request

URL = ('https://storage.googleapis.com/sefaria-export/json/Tanakh/Writings/'
       'Psalms/Hebrew/' + urllib.parse.quote("Tanach with Ta'amei Hamikra") + '.json')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'psalm67.lua')
NOT_LETTER = re.compile('[^\u05d0-\u05ea\\s]')  # points, marks, punctuation
MAQAF = '\u05be'
# Yosef's siddur: (verse, Leningrad spelling) -> siddur spelling.
SIDDUR = {
    (1, 'בנגינת'): 'בנגינות',
    (5, 'מישור'): 'מישר',
    (8, 'אתו'): 'אותו',
}
ELOH = '\u05d0\u05dc\u05d4'          # first three letters of the name


def lua_word(w):
    if w.startswith(ELOH):
        return '"' + ''.join(f'\\u{{{ord(c):04X}}}' for c in w) + '"'
    return '"' + w + '"'


data = json.load(urllib.request.urlopen(URL))
lines = ['-- Psalm 67, Westminster Leningrad Codex (public domain), via the Sefaria',
         "-- export \"Tanach with Ta'amei Hamikra\". Generated by",
         '-- tools/make_psalm67_lua.py; do not edit by hand. Letters only: no',
         '-- nikud, te\'amim or punctuation; maqaf split into separate words.',
         "-- Spellings follow Yosef's siddur where it differs. Words of the",
         '-- divine name Elohim are written as code-point escapes.',
         'return {']
for n, verse in enumerate(data['text'][66], 1):
    words = NOT_LETTER.sub('', verse.replace(MAQAF, ' ')).split()
    for (v, old), new in SIDDUR.items():
        if v == n:
            assert words.count(old) == 1, (n, old)
            words[words.index(old)] = new
    lines.append(f'  -- verse {n}')
    lines.append('  { ' + ', '.join(lua_word(w) for w in words) + ' },')
lines.append('}')
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(OUT))
