#!/usr/bin/env python3
"""Generate ../psalm67.lua from the Sefaria export of Psalm 67.

Usage: python3 make_psalm67_lua.py
Source: "Tanach with Ta'amei Hamikra" (Westminster Leningrad Codex, public
domain), with nikud and te'amim. Words are split on spaces; a paseq is kept
with the word before it. Words of the divine name Elohim are written as
\\u{...} code-point escapes, so the name never appears spelled out in the repo.
"""
import json
import os
import re
import urllib.parse
import urllib.request

URL = ('https://storage.googleapis.com/sefaria-export/json/Tanakh/Writings/'
       'Psalms/Hebrew/' + urllib.parse.quote("Tanach with Ta'amei Hamikra") + '.json')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'psalm67.lua')
PASEQ = '׀'
ELOH = 'אלה'          # first three letters of the name
LETTERS = re.compile('[^א-ת]')


def lua_word(w):
    if LETTERS.sub('', w).startswith(ELOH):
        return '"' + ''.join(f'\\u{{{ord(c):04X}}}' for c in w) + '"'
    return '"' + w + '"'


data = json.load(urllib.request.urlopen(URL))
lines = ['-- Psalm 67, Westminster Leningrad Codex (public domain), via the Sefaria',
         "-- export \"Tanach with Ta'amei Hamikra\". Generated by",
         '-- tools/make_psalm67_lua.py; do not edit by hand. Words of the divine name',
         '-- Elohim are written as code-point escapes.',
         'return {']
for n, verse in enumerate(data['text'][66], 1):
    words = []
    for tok in verse.split():
        if tok == PASEQ and words:
            words[-1] += ' ' + PASEQ
        else:
            words.append(tok)
    lines.append(f'  -- verse {n}')
    lines.append('  { ' + ', '.join(lua_word(w) for w in words) + ' },')
lines.append('}')
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(OUT))
