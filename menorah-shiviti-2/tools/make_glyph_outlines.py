#!/usr/bin/env python3
"""Generate ../glyph-outlines.lua: Stam Sefarad CLM outlines of the letters
Shiviti 2 draws out (he, tav, lamed, dalet, resh, chet).

Usage: python3 make_glyph_outlines.py [path/to/StamSefaradCLM.ttf]
Needs fontTools (pip install fonttools). The default font path is TeX Live's.

menorah.lua draws a drawn-out letter as one filled shape built from these
outlines, widening only its plain horizontal stroke, instead of clipping
slices of the typeset glyph: clipping is ignored by some SVG importers and
laser software. Coordinates are font units (y up, origin at the left end of
the baseline); every curve is cubic. The font is GPL with the font
exception (Culmus Project).
"""
import os
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

FONT = (sys.argv[1] if len(sys.argv) > 1 else
        '/usr/share/texlive/texmf-dist/fonts/truetype/public/culmus/StamSefaradCLM.ttf')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'glyph-outlines.lua')
LETTERS = [0x05D4, 0x05EA, 0x05DC, 0x05D3, 0x05E8, 0x05D7]


class LuaPen(BasePen):
    """Records a glyph as Lua path operations, quadratics raised to cubics."""

    def __init__(self, glyphset):
        super().__init__(glyphset)
        self.ops = []

    def _moveTo(self, p):
        self.ops.append('{ "m", %g, %g }' % p)

    def _lineTo(self, p):
        self.ops.append('{ "l", %g, %g }' % p)

    def _curveToOne(self, p1, p2, p3):
        self.ops.append('{ "c", %g, %g, %g, %g, %g, %g }' % (*p1, *p2, *p3))

    def _qCurveToOne(self, p1, p2):
        p0 = self._getCurrentPoint()
        c1 = (p0[0] + 2 / 3 * (p1[0] - p0[0]), p0[1] + 2 / 3 * (p1[1] - p0[1]))
        c2 = (p2[0] + 2 / 3 * (p1[0] - p2[0]), p2[1] + 2 / 3 * (p1[1] - p2[1]))
        self._curveToOne(c1, c2, p2)

    def _closePath(self):
        self.ops.append('{ "z" }')


font = TTFont(FONT)
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
lines = ['-- Stam Sefarad CLM outlines of the letters Shiviti 2 draws out.',
         '-- Generated by tools/make_glyph_outlines.py; do not edit by hand.',
         '-- Font units, y up; units_per_em and each letter\'s advance width.',
         'return {',
         '  units_per_em = %d,' % font['head'].unitsPerEm]
for cp in LETTERS:
    name = cmap[cp]
    pen = LuaPen(glyphs)
    glyphs[name].draw(pen)
    lines.append('  [0x%04X] = { advance = %d, path = {' % (cp, glyphs[name].width))
    lines.extend('    %s,' % op for op in pen.ops)
    lines.append('  } },')
lines.append('}')
with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(OUT))
