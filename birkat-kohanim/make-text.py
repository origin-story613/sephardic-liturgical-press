#!/usr/bin/env python3
"""Write birkat-kohanim/text.lua: Numbers 6:24-26, letters only.

Usage: python3 -I make-text.py "<path to Numbers/Hebrew/Tanach with Ta'amei Hamikra.json>"

Source: the Sefaria export of the Westminster Leningrad Codex (see
sources.md). Vowels, cantillation, the paseq, the sof pasuq and the section
marks are removed. The Name is written to the file as the token NAME and
assembled from code points by spiral.lua, so it never appears in any file.
"""
import json
import re
import sys

chapter = json.load(open(sys.argv[1], encoding='utf-8'))['text'][5]
NAME = re.compile(''.join(chr(c) for c in (0x05D9, 0x05D4, 0x05D5, 0x05D4)))

verses = []
for v in chapter[23:26]:                            # 6:24, 6:25, 6:26
    v = re.sub(r'\([^)]*\)|<[^>]*>', ' ', v)        # (ס), markup
    v = v.replace('־', ' ')                    # maqaf
    v = re.sub('[֑-ׇ]', '', v)            # points, te'amim, paseq, sof pasuq
    words = ['NAME' if NAME.fullmatch(w) else w for w in v.split()]
    for w in words:
        if w != 'NAME' and not all('א' <= c <= 'ת' for c in w):
            sys.exit('unexpected characters in ' + w)
    verses.append(words)

with open('text.lua', 'w', encoding='utf-8') as f:
    f.write('-- birkat-kohanim/text.lua: Numbers 6:24-26, letters only.\n'
            '-- Generated by make-text.py; do not edit by hand. NAME marks the\n'
            '-- Name, assembled from code points in spiral.lua.\n'
            'return {\n')
    for words in verses:
        f.write('  { ' + ', '.join("'%s'" % w for w in words) + ' },\n')
    f.write('}\n')
for words in verses:
    print(len(words), 'words,', sum(4 if w == 'NAME' else len(w) for w in words), 'letters')
