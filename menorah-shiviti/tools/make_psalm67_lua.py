#!/usr/bin/env python3
"""Generate ../psalm67.lua from the Sefaria export of Psalm 67.

Usage: python3 make_psalm67_lua.py
Source: "Tanach with Ta'amei Hamikra" (Westminster Leningrad Codex, public
domain), with nikud and te'amim. Punctuation is removed (Yosef): sof pasuq
and paseq are dropped, and a maqaf becomes a word break. Words of the divine
name Elohim are written as \\u{...} code-point escapes, so the name never
appears spelled out in the repo.
"""
import json
import os
import re
import urllib.parse
import urllib.request

URL = ('https://storage.googleapis.com/sefaria-export/json/Tanakh/Writings/'
       'Psalms/Hebrew/' + urllib.parse.quote("Tanach with Ta'amei Hamikra") + '.json')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'psalm67.lua')
PUNCT = re.compile('[\u05c0\u05c3]')   # paseq, sof pasuq
MAQAF = '\u05be'
ELOH = '\u05d0\u05dc\u05d4'          # first three letters of the name
LETTERS = re.compile('[^א-ת]')


def lua_word(w):
    if LETTERS.sub('', w).startswith(ELOH):
        return '"' + ''.join(f'\\u{{{ord(c):04X}}}' for c in w) + '"'
    return '"' + w + '"'


data = json.load(urllib.request.urlopen(URL))
lines = ['-- Psalm 67, Westminster Leningrad Codex (public domain), via the Sefaria',
         "-- export \"Tanach with Ta'amei Hamikra\". Generated by",
         '-- tools/make_psalm67_lua.py; do not edit by hand. Punctuation removed',
         '-- (sof pasuq, paseq; maqaf split into separate words). Words of the',
         '-- divine name Elohim are written as code-point escapes.',
         'return {']
for n, verse in enumerate(data['text'][66], 1):
    words = PUNCT.sub('', verse).replace(MAQAF, ' ').split()
    lines.append(f'  -- verse {n}')
    lines.append('  { ' + ', '.join(lua_word(w) for w in words) + ' },')
lines.append('}')
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(OUT))
