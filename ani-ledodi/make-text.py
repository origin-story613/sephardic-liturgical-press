#!/usr/bin/env python3
"""Write ani-ledodi/text.tex: the whole of Shir HaShirim, letters only.

Usage: python3 -I make-text.py "<path to Tanach with Ta'amei Hamikra.json>"

Source: the Sefaria export of the Westminster Leningrad Codex (see
sources.md). Vowels and cantillation are removed; a maqaf becomes a space
and the paseq, the sof pasuq and the section marks (ס)/(פ) are dropped, so
the text is one continuous run of words. Where the written and the read
form differ (ketiv/qere), the written form is kept and the bracketed read
form dropped (provisional; see sources.md).
"""
import json
import re
import sys

src = sys.argv[1]
chapters = json.load(open(src, encoding='utf-8'))['text']

words = []
for chapter in chapters:
    for verse in chapter:
        v = re.sub(r'\[[^\]]*\]', ' ', verse)          # qere (read form)
        v = re.sub(r'\([^)]*\)|<[^>]*>', ' ', v)        # (ס), (פ), markup
        v = v.replace('־', ' ')                     # maqaf
        v = re.sub('[֑-ׇ]', '', v)             # points, te'amim,
                                                         # paseq, sof pasuq
        words += v.split()

text = ' '.join(words)
bad = sorted(set(c for c in text if not ('א' <= c <= 'ת' or c == ' ')))
if bad:
    sys.exit('unexpected characters: ' + ' '.join('%04X' % ord(c) for c in bad))

lines, line = [], ''
for w in words:                       # wrap the file at about 72 characters
    if line and len(line) + 1 + len(w) > 72:
        lines.append(line)
        line = w
    else:
        line = (line + ' ' + w).strip()
lines.append(line)

with open('text.tex', 'w', encoding='utf-8') as f:
    f.write('% ani-ledodi/text.tex: Shir HaShirim, letters only.\n'
            '% Generated by make-text.py; do not edit by hand.\n')
    f.write('\n'.join(lines) + '\n')     # a line end reads as a space
print(len(words), 'words,', sum(len(w) for w in words), 'letters')
